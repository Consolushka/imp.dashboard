// Ответы приходят в любом порядке: при быстрой смене турнира ответ на старый запрос может прийти последним
// и затереть данные нового. Каждый запуск загрузки получает проверку «я всё ещё последний?» —
// ответ опоздавшего запроса блок просто выбрасывает.
export const latestOnly = () => {
  let current = 0
  return () => {
    const id = ++current
    return () => id === current
  }
}
